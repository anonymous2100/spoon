test('getStagedPatch / getWorkingPatch / changeBrief describe pending work', async () => {
  const repo = makeRepo('brief', { 'a.txt': 'a\n' })
  write(repo, 'a.txt', 'a2\n')
  sh(repo, ['add', 'a.txt'])
  write(repo, 'new.ts', 'export const x = 1\n')
  assert.match(await git.getStagedPatch(repo), /\+a2/)
  const working = await git.getWorkingPatch(repo)
  assert.match(working, /\+a2/)
  assert.match(working, /Untracked: new\.ts/)
  const brief = await git.changeBrief(repo)
  const by = Object.fromEntries(brief.map((f) => [f.path, f]))
  assert.match(by['a.txt'].status, /staged M/)
  assert.match(by['a.txt'].patch, /\+a2/)
  assert.equal(by['new.ts'].status, 'untracked')
  assert.match(by['new.ts'].patch, /export const x/)
})

