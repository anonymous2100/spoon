test('stage / unstage / stageAll / unstageAll move files between the lists', async () => {
  const repo = makeRepo('staging', { 'a.txt': 'a\n' })
  write(repo, 'a.txt', 'a2\n')
  write(repo, 'b.txt', 'b\n')
  write(repo, 'with space.txt', 's\n')
  await git.stage(repo, ['a.txt', 'with space.txt'])
  let st = await git.getStatus(repo)
  assert.deepEqual(st.staged.map((e) => e.path).sort(), ['a.txt', 'with space.txt'])
  await git.unstage(repo, ['a.txt'])
  st = await git.getStatus(repo)
  assert.deepEqual(st.staged.map((e) => e.path), ['with space.txt'])
  await git.stageAll(repo)
  st = await git.getStatus(repo)
  assert.equal(st.stagedCount, 3)
  assert.equal(st.unstagedCount, 0)
  await git.unstageAll(repo)
  st = await git.getStatus(repo)
  assert.equal(st.stagedCount, 0)
  await git.stage(repo, [])
  await git.unstage(repo, [])
})

