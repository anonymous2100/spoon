test('getDiff returns unstaged, staged, per-path, per-commit and whitespace-insensitive diffs', async () => {
  const repo = makeRepo('diff', { 'a.txt': lines(10), 'b.txt': 'b\n' })
  write(repo, 'a.txt', lines(10, { 3: 'three' }))
  write(repo, 'b.txt', 'b  \n')
  const unstaged = await git.getDiff(repo)
  assert.deepEqual(unstaged.map((f) => f.path).sort(), ['a.txt', 'b.txt'])
  const onlyA = await git.getDiff(repo, { path: 'a.txt' })
  assert.equal(onlyA.length, 1)
  const hunk = onlyA[0].hunks[0]
  assert.ok(hunk.lines.some((l) => l.type === 'del' && l.text === 'line 3' && l.oldNo === 3))
  assert.ok(hunk.lines.some((l) => l.type === 'add' && l.text === 'three' && l.newNo === 3))
  const ws = await git.getDiff(repo, { ignoreWhitespace: true })
  assert.deepEqual(ws.filter((f) => f.hunks.length).map((f) => f.path), ['a.txt'])
  await git.stage(repo, ['a.txt'])
  const staged = await git.getDiff(repo, { staged: true })
  assert.deepEqual(staged.map((f) => f.path), ['a.txt'])
  const sha = commitAll(repo, 'edit')
  const shown = await git.getDiff(repo, { commit: sha })
  assert.deepEqual(shown.map((f) => f.path).sort(), ['a.txt', 'b.txt'])
  const ctx = await git.getDiff(repo, { commit: sha, path: 'a.txt', context: 0 })
  assert.equal(ctx[0].hunks[0].lines.filter((l) => l.type === 'context').length, 0)
})

test('parseDiffs detects new, deleted, renamed and binary files', async () => {
  const repo = makeRepo('kinds', { 'del.txt': 'x\n', 'from.txt': 'same content here\nmore\nlines\n' })
  unlinkSync(join(repo, 'del.txt'))
  renameSync(join(repo, 'from.txt'), join(repo, 'to.txt'))
  write(repo, 'new.txt', 'n\n')
  write(repo, 'bin.png', Buffer.from([0, 1, 2, 3, 0, 255]))
  sh(repo, ['add', '-A'])
  const files = await git.getDiff(repo, { staged: true })
  const by = Object.fromEntries(files.map((f) => [f.path, f]))
  assert.equal(by['del.txt'].status, 'D')
  assert.equal(by['new.txt'].status, 'A')
  assert.equal(by['to.txt'].status, 'R')
  assert.equal(by['to.txt'].origPath, 'from.txt')
  assert.equal(by['bin.png'].binary, true)
  assert.equal(by['bin.png'].image, true)
})

