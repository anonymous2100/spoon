test('applyHunk stages, unstages and discards a single hunk', async () => {
  const repo = makeRepo('hunks', { 'f.txt': lines(40) })
  write(repo, 'f.txt', lines(40, { 2: 'TOP', 38: 'BOTTOM' }))
  const [file] = await git.getDiff(repo, { path: 'f.txt' })
  assert.equal(file.hunks.length, 2)
  await git.applyHunk(repo, 'f.txt', file.hunks[0], 'stage')
  const staged = await git.getDiff(repo, { staged: true })
  assert.equal(staged[0].hunks.length, 1)
  assert.ok(staged[0].hunks[0].lines.some((l) => l.text === 'TOP'))
  await git.applyHunk(repo, 'f.txt', staged[0].hunks[0], 'unstage')
  assert.equal((await git.getDiff(repo, { staged: true })).length, 0)
  const [again] = await git.getDiff(repo, { path: 'f.txt' })
  await git.applyHunk(repo, 'f.txt', again.hunks[1], 'discard')
  const text = readFileSync(join(repo, 'f.txt'), 'utf8')
  assert.match(text, /TOP/)
  assert.doesNotMatch(text, /BOTTOM/)
})

