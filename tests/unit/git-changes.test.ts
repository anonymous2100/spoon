// Working tree features: status, staging, hunks, discard, commit, diffs, patches.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { existsSync, readFileSync, unlinkSync, renameSync } from 'node:fs'
import { join } from 'node:path'
import * as git from '../../src/main/git.ts'
import { commitAll, head, log, makeRepo, sh, write } from '../support/repo.ts'

const lines = (n: number, edit: Record<number, string> = {}) =>
  Array.from({ length: n }, (_, i) => edit[i + 1] ?? `line ${i + 1}`).join('\n') + '\n'

test('isRepo / repoInfo / repoRoot recognise a work tree and reject plain folders', async () => {
  const repo = makeRepo()
  write(repo, 'src/deep/a.txt', 'x')
  assert.equal(await git.isRepo(repo), true)
  assert.equal(await git.isRepo(join(repo, 'src', 'deep')), true)
  assert.equal(await git.isRepo(join(repo, 'missing')), false)
  assert.equal(await git.isRepo(join(repo, '..')), false)
  const info = await git.repoInfo(join(repo, 'src'))
  assert.equal(info?.root.toLowerCase(), repo.toLowerCase())
  assert.equal(info?.gitDir.toLowerCase(), join(repo, '.git').toLowerCase())
  assert.equal((await git.repoRoot(join(repo, 'src'))).toLowerCase(), repo.toLowerCase())
  assert.equal(await git.repoName(repo), 'repo')
})

test('getStatus classifies staged, unstaged, untracked, renamed and deleted files', async () => {
  const repo = makeRepo('status', { 'a.txt': 'a\n', 'b.txt': 'b\n', 'old name.txt': 'rename me\n', 'gone.txt': 'bye\n' })
  write(repo, 'a.txt', 'a changed\n')
  sh(repo, ['add', 'a.txt'])
  write(repo, 'b.txt', 'b changed\n')
  write(repo, 'new file ñ.txt', 'hola\n')
  sh(repo, ['mv', 'old name.txt', 'new name.txt'])
  unlinkSync(join(repo, 'gone.txt'))
  const st = await git.getStatus(repo)
  assert.equal(st.branch, 'main')
  assert.equal(st.detached, false)
  const staged = Object.fromEntries(st.staged.map((e) => [e.path, e]))
  assert.equal(staged['a.txt'].index, 'M')
  assert.equal(staged['new name.txt'].index, 'R')
  assert.equal(staged['new name.txt'].origPath, 'old name.txt')
  const unstaged = st.unstaged.map((e) => e.path).sort()
  assert.deepEqual(unstaged, ['b.txt', 'gone.txt', 'new file ñ.txt'])
  assert.deepEqual(st.untracked.map((e) => e.path), ['new file ñ.txt'])
  assert.equal(st.stagedCount, 2)
  assert.equal(st.unstagedCount, 3)
})

