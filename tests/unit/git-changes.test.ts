test('getStatus reports conflicted files with their real path', async () => {
  const repo = makeRepo('conflict', { 'shared.txt': 'base\n' })
  sh(repo, ['checkout', '-q', '-b', 'other'])
  write(repo, 'shared.txt', 'theirs\n')
  commitAll(repo, 'other side')
  sh(repo, ['checkout', '-q', 'main'])
  write(repo, 'shared.txt', 'ours\n')
  commitAll(repo, 'main side')
  const merged = await git.mergeBranch(repo, 'other')
  assert.notEqual(merged.code, 0)
  const st = await git.getStatus(repo)
  assert.equal(st.merging, true)
  assert.deepEqual(st.conflicted.map((e) => e.path), ['shared.txt'])
})

