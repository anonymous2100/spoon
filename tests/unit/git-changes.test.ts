test('commit creates commits, supports amend, sign-off and no-verify', async () => {
  const repo = makeRepo()
  write(repo, 'a.txt', 'a')
  await git.stageAll(repo)
  await git.commit(repo, { message: 'feat: add a' })
  assert.deepEqual(log(repo), ['feat: add a', 'Initial commit'])
  write(repo, 'b.txt', 'b')
  await git.stageAll(repo)
  await git.commit(repo, { message: 'feat: add a and b', amend: true })
  assert.deepEqual(log(repo), ['feat: add a and b', 'Initial commit'])
  assert.match(sh(repo, ['show', '--name-only', '--format=', 'HEAD']), /b\.txt/)
  write(repo, 'c.txt', 'c')
  await git.stageAll(repo)
  write(repo, '.git/hooks/pre-commit', '#!/bin/sh\nexit 1\n')
  await assert.rejects(git.commit(repo, { message: 'blocked by hook' }))
  await git.commit(repo, { message: 'skip hooks', noVerify: true, signOff: true })
  assert.match(sh(repo, ['log', '-1', '--format=%B']), /Signed-off-by: Spoon Test <spoon-test@example.com>/)
})

